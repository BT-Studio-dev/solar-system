#!/usr/bin/env python3
"""Bake the screenshot-harness glyph atlas (src/font_baked.h).

The Windows application draws text with GDI+ (Segoe UI / Consolas), so this
atlas is only consumed by src/gfx_soft.c, the headless renderer used by the
automated screenshot tests.

Run:  python tools/bake_fonts.py
"""
from __future__ import annotations

import io
import os
import sys
import tempfile

from fontTools.ttLib import TTFont
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONTS = os.path.join(ROOT, "tools", "fonts")
OUT = os.path.join(ROOT, "src", "font_baked.h")

# (variable name, file, pixel size, label)
FACES = [
    ("font_ui", "opensans-regular.woff2", 12, "UI"),
    ("font_ui_small", "opensans-regular.woff2", 11, "UI small"),
    ("font_ui_bold", "opensans-semibold.woff2", 12, "UI bold"),
    ("font_ui_tiny", "opensans-regular.woff2", 10, "UI tiny"),
    ("font_h1", "opensans-semibold.woff2", 20, "H1"),
    ("font_h2", "opensans-semibold.woff2", 15, "H2"),
    ("font_hero", "opensans-light.woff2", 42, "Hero"),
    ("font_mono", "robotomono-regular.woff2", 11, "Mono"),
    ("font_mono_big", "robotomono-regular.woff2", 18, "Mono big"),
]

EXTRA_CODEPOINTS = [
    0x00B0, 0x00B1, 0x00B5, 0x00B7, 0x00B2, 0x00B3, 0x00BD, 0x00D7, 0x00F7,
    0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2026, 0x2032, 0x2033,
    0x2190, 0x2192, 0x2191, 0x2193, 0x2212, 0x221E, 0x2248, 0x2260, 0x2264, 0x2265,
    0x25B2, 0x25BC, 0x25C0, 0x25B6, 0x25CF, 0x25CB, 0x2605, 0x2606, 0x2713,
    0x03A9, 0x00B0,
    # astronomy symbols (only kept when the face provides them)
    0x2609, 0x263F, 0x2640, 0x2641, 0x2642, 0x2643, 0x2644, 0x2645, 0x2646, 0x2604,
]

ATLAS_W = 1024


def load_ttf(woff2: str) -> str:
    ttf = TTFont(os.path.join(FONTS, woff2))
    ttf.flavor = None
    tmp = tempfile.NamedTemporaryFile(suffix=".ttf", delete=False)
    tmp.close()
    ttf.save(tmp.name)
    return tmp.name


def main() -> int:
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    atlas = Image.new("L", (ATLAS_W, 2048), 0)
    cursor_x, cursor_y, shelf_h = 1, 1, 0
    glyph_blocks = []
    font_blocks = []
    used_atlas_h = 1

    for var, filename, px, label in FACES:
        path = load_ttf(filename)
        font = ImageFont.truetype(path, px, layout_engine=ImageFont.Layout.BASIC)
        os.unlink(path)
        cmap = TTFont(os.path.join(FONTS, filename)).getBestCmap()
        cps = [cp for cp in list(range(32, 127)) + sorted(set(EXTRA_CODEPOINTS)) if cp in cmap]
        ascent, descent = font.getmetrics()
        glyphs = []
        draw = ImageDraw.Draw(atlas)
        for cp in cps:
            ch = chr(cp)
            advance = font.getlength(ch)
            x0, y0, x1, y1 = draw.textbbox((0, 0), ch, font=font, anchor="ls")
            w, h = max(0, x1 - x0), max(0, y1 - y0)
            if w > 0 and h > 0:
                if cursor_x + w + 2 > ATLAS_W:
                    cursor_x = 1
                    cursor_y += shelf_h + 2
                    shelf_h = 0
                mask = Image.new("L", (w, h), 0)
                md = ImageDraw.Draw(mask)
                md.text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
                atlas.paste(mask, (cursor_x, cursor_y))
                gx, gy = cursor_x, cursor_y
                cursor_x += w + 2
                shelf_h = max(shelf_h, h)
                used_atlas_h = max(used_atlas_h, cursor_y + h + 1)
            else:
                gx = gy = 0
            glyphs.append((cp, gx, gy, w, h, int(round(x0)), int(round(y0)), int(round(advance * 64))))
        font_blocks.append((var, px, ascent, descent, glyphs, label))
        print(f"{label:9s} {filename:26s} {px:2d}px  glyphs={len(glyphs):3d}  atlas row={cursor_y}")

    atlas = atlas.crop((0, 0, ATLAS_W, used_atlas_h))
    data = atlas.tobytes()

    with open(OUT, "w", encoding="utf-8") as f:
        f.write("/* font_baked.h -- generated by tools/bake_fonts.py. Do not edit. */\n")
        f.write("#ifndef SSS_FONT_BAKED_H\n#define SSS_FONT_BAKED_H\n\n#include <stdint.h>\n\n")
        f.write("typedef struct {\n    uint32_t cp;\n    int16_t x, y, w, h;\n")
        f.write("    int16_t bearing_x, bearing_y;\n    int16_t advance64;\n} BakedGlyph;\n\n")
        f.write("typedef struct {\n    int px, ascent, descent, line_h;\n    const BakedGlyph *glyphs;\n")
        f.write("    int glyph_count;\n    const uint8_t *bitmap;\n    int atlas_w, atlas_h;\n} BakedFont;\n\n")
        f.write(f"#define BAKED_ATLAS_W {atlas.width}\n#define BAKED_ATLAS_H {atlas.height}\n\n")
        f.write("static const uint8_t baked_atlas[] = {\n")
        for i in range(0, len(data), 32):
            f.write("    " + ",".join(str(b) for b in data[i:i + 32]) + ",\n")
        f.write("};\n\n")
        for idx, (var, px, ascent, descent, glyphs, label) in enumerate(font_blocks):
            f.write(f"/* {label} */\nstatic const BakedGlyph {var}_glyphs[] = {{\n")
            for g in glyphs:
                f.write("    {%d,%d,%d,%d,%d,%d,%d,%d},\n" % g)
            f.write("};\n")
        f.write("\nstatic const BakedFont baked_fonts[9] = {\n")
        for idx, (var, px, ascent, descent, glyphs, label) in enumerate(font_blocks):
            f.write("    {%d,%d,%d,%d,%s_glyphs,%d,baked_atlas,BAKED_ATLAS_W,BAKED_ATLAS_H}, /* %s */\n"
                    % (px, ascent, descent, ascent + descent + 2, var, len(glyphs), label))
        f.write("};\n\n#endif\n")
    print(f"wrote {OUT}: atlas {atlas.width}x{atlas.height}, {len(data)/1024:.0f} KiB, header "
          f"{os.path.getsize(OUT)/1024:.0f} KiB")
    return 0


if __name__ == "__main__":
    sys.exit(main())
